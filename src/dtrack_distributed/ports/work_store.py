from __future__ import annotations

from typing import Any, Protocol


class WorkStore(Protocol):
    def put_json(self, key: str, value: Any) -> str: ...
    def get_json(self, key: str) -> Any: ...
    def put_bytes(self, key: str, body: bytes, *, content_type: str) -> str: ...
    def exists(self, key: str) -> bool: ...
    def list_keys(self, prefix: str, *, start_after: str | None = None) -> list[str]: ...
    def list_json(
        self, prefix: str, *, start_after: str | None = None
    ) -> list[tuple[str, Any]]: ...
